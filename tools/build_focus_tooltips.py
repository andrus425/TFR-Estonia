"""Generate TFR-style native previews for Estonia's dynamic-modifier rewards.

These country ideas are display-only definitions. An effect_tooltip swap from
an empty idea to a delta idea lets HOI4 render its native modifier labels,
percentages and colors. Actual rewards update the two persistent modifiers;
neither preview idea should ever be added to a country.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
CATEGORIES = {
    "economy": "generic_emerging_economy",
    "military": "generic_military_org",
}


def focus_rewards():
    """Read the same final reward values that the focus generators apply.

    Imports remain local because the content generators may also import small
    formatting helpers from other tooling modules while they are initialized.
    """
    from build_opening_content import POLICIES as opening
    from build_ratas_continuation import POLICIES as ratas
    from build_kallas_continuation import POLICIES as kallas
    from build_reform_2023 import POLICIES as reform_2023
    from build_ekre_2023 import POLICIES as ekre_2023
    from build_centre_2023 import POLICIES as centre_2023
    from build_isamaa_2023 import POLICIES as isamaa_2023
    from build_sde_2023 import POLICIES as sde_2023
    from build_e200_2023 import POLICIES as e200_2023
    from build_pp_2023 import POLICIES as pp_2023
    from focus_reward_model import OPENING_ECONOMIC, OPENING_MILITARY

    rewards = {}
    for policy in opening:
        rewards["TFR_EST_opening_" + policy.suffix] = {
            "economy": tuple(OPENING_ECONOMIC.get(policy.suffix, ())),
            "military": tuple(OPENING_MILITARY.get(policy.suffix, ())),
        }
    for route, policies in (("ratas", ratas), ("kallas", kallas), ("reform_2023", reform_2023), ("ekre_2023", ekre_2023), ("centre_2023", centre_2023), ("isamaa_2023", isamaa_2023), ("sde_2023", sde_2023), ("e200_2023", e200_2023), ("pp_2023", pp_2023)):
        for policy in policies:
            rewards[f"TFR_EST_{route}_{policy.suffix}"] = {
                "economy": tuple(policy.economic),
                "military": tuple(policy.military),
            }
    return rewards


def idea_definitions():
    """Return ID, modifier category and exact numerical delta for each idea."""
    definitions = {
        f"TFR_EST_tooltip_{category}_empty": (category, ())
        for category in CATEGORIES
    }
    for focus_id, rewards in focus_rewards().items():
        for category, changes in rewards.items():
            if changes:
                definitions[f"{focus_id}_{category}_delta"] = (category, changes)
    return definitions


def build_ideas():
    out = [
        "# Generated by tools/build_focus_tooltips.py.\n",
        "# Display-only country ideas, matching TFR's German dynamic previews.\n",
        "# Use only inside effect_tooltip; no country receives these ideas.\n",
        "ideas = {\n    country = {\n",
    ]
    for ident, (category, changes) in idea_definitions().items():
        out.append(f"""        {ident} = {{
            name = TFR_EST_{category}_dynamic
            picture = {CATEGORIES[category]}
            allowed = {{ original_tag = EST }}
            modifier = {{
""")
        for field, amount in changes:
            out.append(f"                {field} = {amount:.12g}\n")
        out.append("            }\n        }\n")
    out.append("    }\n}\n")
    return "".join(out)


def build_localisation():
    # The game reads each idea's explicit name. Aliases also keep ID-based
    # localization checks and diagnostic tools useful without duplicate prose.
    out = ["l_english:\n"]
    for ident, (category, _) in idea_definitions().items():
        for suffix in ("", "_desc"):
            alias = f"$TFR_EST_{category}_dynamic{suffix}$"
            out.append(f" {ident}{suffix}:0 {json.dumps(alias)}\n")
    return "".join(out)


def outputs():
    return {
        "common/ideas/TFR_EST_focus_tooltips.txt": build_ideas(),
        "localisation/english/TFR_EST_focus_tooltips_l_english.yml": build_localisation(),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for relative, text in outputs().items():
        path = ROOT / relative
        data = text.encode("utf-8-sig" if path.suffix == ".yml" else "utf-8")
        if args.check:
            if not path.is_file() or path.read_bytes() != data:
                raise SystemExit(f"Generated focus preview is stale: {relative}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    print(("Verified" if args.check else "Wrote") +
          f" {len(idea_definitions())} display-only modifier previews.")


if __name__ == "__main__":
    main()
