"""Register the seven 2023 programmes' explicitly mapped focus artwork.

The tracked artwork catalog assigns a unique texture to every focus.
Every focus keeps its own sprite identity and TFR's two-pass shine animation.
"""
from __future__ import annotations

from functools import lru_cache
import json
from pathlib import Path
import re


ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / "docs/artwork/post2023/catalog.json"
PARTIES = ("reform", "ekre", "centre", "isamaa", "sde", "e200", "pp")


@lru_cache(maxsize=1)
def _catalog() -> dict[str, dict]:
    trees = json.loads(CATALOG.read_text(encoding="utf-8"))["trees"]
    by_party = {tree["party"]: tree for tree in trees}
    if len(by_party) != len(trees) or set(by_party) != set(PARTIES):
        raise ValueError("The 2023 artwork catalog must cover each of the seven parties once")
    return by_party


def focus_sprite(party: str, suffix: str) -> str:
    """Give every focus its own engine sprite name."""
    if party not in PARTIES:
        raise ValueError(f"Unknown 2023 artwork party: {party}")
    return f"GFX_goal_TFR_EST_{party}_2023_{suffix}"


def focus_art_map(party: str, policies) -> dict[str, str]:
    """Require 32 authored policies and 32 distinct assets, one per focus."""
    tree = _catalog()[party]
    prefix = f"TFR_EST_{party}_2023_"
    expected = {policy.suffix for policy in policies}
    focuses = tree["focuses"]
    mapping = {focus["suffix"]: focus["recommended_asset"] for focus in focuses}
    if len(policies) != 32 or len(expected) != 32:
        raise ValueError(f"The {party} 2023 programme must contain 32 unique focuses")
    if len(focuses) != 32 or set(mapping) != expected:
        missing, extra = expected - mapping.keys(), mapping.keys() - expected
        raise ValueError(f"The {party} artwork mapping differs from its policies: {missing=}, {extra=}")
    if tree["prefix"] != prefix or any(
        focus["focus_id"] != prefix + focus["suffix"] for focus in focuses
    ):
        raise ValueError(f"The {party} artwork catalog has inconsistent focus identities")
    declared = tree["recommended_assets"]
    assets = {asset["asset_id"] for asset in declared}
    if len(declared) != 32 or len(assets) != 32 or len(set(mapping.values())) != 32:
        raise ValueError(f"The {party} artwork catalog must assign 32 distinct assets, one per focus")
    if set(mapping.values()) != assets or any(
        not re.fullmatch(r"[a-z][a-z0-9_]*", asset) for asset in assets
    ):
        raise ValueError(f"The {party} artwork mapping contains missing, unused or invalid assets")
    for asset in declared:
        assigned = [suffix for suffix, key in mapping.items() if key == asset["asset_id"]]
        if asset["focus_suffixes"] != assigned or asset["focus_ids"] != [prefix + assigned[0]]:
            raise ValueError(f"The {party}/{asset['asset_id']} artwork must describe exactly its assigned focus")
    return mapping


def build_focus_sprites(policies, party: str, generator_name: str) -> str:
    """Register base sprites and the same highlight passes as TFR's goals."""
    mapping = focus_art_map(party, policies)
    pieces = [
        f"# Generated by tools/{generator_name}.\n"
        "# Focus-to-texture mapping: docs/artwork/post2023/catalog.json.\n"
        "# Shine animation matches TFR_goals_shine.gfx in the parent mod.\n"
        "spriteTypes = {\n"
    ]
    for policy in policies:
        name = focus_sprite(party, policy.suffix)
        texture = f"gfx/interface/goals/EST/EST_{party}_2023_{mapping[policy.suffix]}.png"
        pieces.append(
            f"    SpriteType = {{\n"
            f'        name = "{name}"\n'
            f'        texturefile = "{texture}"\n'
            f"    }}\n"
            f"    SpriteType = {{\n"
            f'        name = "{name}_shine"\n'
            f'        texturefile = "{texture}"\n'
            f'        effectFile = "gfx/FX/buttonstate.lua"\n'
        )
        for rotation in (-90.0, 90.0):
            pieces.append(
                f"        animation = {{\n"
                f'            animationmaskfile = "{texture}"\n'
                f'            animationtexturefile = "gfx/interface/goals/shine_overlay.dds"\n'
                f"            animationrotation = {rotation}\n"
                f"            animationlooping = no\n"
                f"            animationtime = 0.75\n"
                f"            animationdelay = 0\n"
                f'            animationblendmode = "add"\n'
                f'            animationtype = "scrolling"\n'
                f"            animationrotationoffset = {{ x = 0.0 y = 0.0 }}\n"
                f"            animationtexturescale = {{ x = 1.0 y = 1.0 }}\n"
                f"        }}\n"
            )
        pieces.append("        legacy_lazy_load = no\n    }\n")
    pieces.append("}\n")
    return "".join(pieces)
