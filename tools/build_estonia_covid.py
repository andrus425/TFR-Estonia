"""Build Estonia's first-case bridge into TFR's existing COVID severity ideas.

The Health Board announced Estonia's first confirmed case on 27 February 2020:
https://terviseamet.ee/uudised/eestis-diagnoositi-esimene-covid-19-haigusjuhtum
This is a country event, independent of whether the response focus is selected.
The bridge supplies the missing Estonia outbreak hook, not a new disease model.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]


def build_effects() -> str:
    return """# Generated by tools/build_estonia_covid.py; do not edit by hand.
# TFR's generic_has_corona reads the five parent COVID national ideas.
# The one-time country event supplies Estonia's otherwise absent outbreak hook.
TFR_EST_register_covid_first_case = {
    if = {
        limit = {
            tag = EST
            date > 2020.2.26
            date < 2023.1.1
            NOT = { has_country_flag = TFR_EST_covid_first_case_recorded }
        }
        set_country_flag = TFR_EST_covid_first_case_recorded
        clr_country_flag = TFR_EST_covid_first_case_pending
        if = {
            limit = { NOT = { generic_has_corona = yes } }
            add_ideas = lower_covid_cases
            set_country_flag = TFR_EST_covid_seed_owned
        }
        log = "TFR_EST_COVID_FIRST_CASE_RECORDED"
    }
}

TFR_EST_covid_tick = {
    if = {
        limit = { tag = EST }
        # A changed or recovered severity no longer belongs to this bridge.
        if = {
            limit = {
                has_country_flag = TFR_EST_covid_seed_owned
                NOT = { has_idea = lower_covid_cases }
            }
            clr_country_flag = TFR_EST_covid_seed_owned
        }
        # Respect any existing parent/mod outbreak, whatever its severity.
        if = {
            limit = {
                generic_has_corona = yes
                NOT = { has_country_flag = TFR_EST_covid_first_case_recorded }
            }
            set_country_flag = TFR_EST_covid_first_case_recorded
            clr_country_flag = TFR_EST_covid_first_case_pending
        }
        # Match the parent ideas' available period after the mandatory response.
        # Keep an unfinished response reachable if the player delays beyond 2022.
        # Never remove another tier or an externally owned infection.
        if = {
            limit = {
                NOT = { date < 2023.1.1 }
                has_country_flag = TFR_EST_covid_seed_owned
                has_idea = lower_covid_cases
                OR = {
                    has_country_flag = TFR_EST_done_opening_covid_emergency
                    has_completed_focus = TFR_EST_opening_covid_emergency
                }
            }
            remove_ideas = lower_covid_cases
            clr_country_flag = TFR_EST_covid_seed_owned
        }
        if = {
            limit = {
                date > 2020.2.26
                date < 2023.1.1
                NOT = { has_country_flag = TFR_EST_covid_first_case_recorded }
                NOT = { has_country_flag = TFR_EST_covid_first_case_pending }
            }
            set_country_flag = { flag = TFR_EST_covid_first_case_pending days = 2 }
            country_event = { id = tfr_estonia_covid.1 hours = 1 }
        }
    }
}
"""


def build_events() -> str:
    return """# Generated by tools/build_estonia_covid.py; do not edit by hand.
add_namespace = tfr_estonia_covid

country_event = {
    id = tfr_estonia_covid.1
    title = TFR_EST_covid_first_case_title
    desc = TFR_EST_covid_first_case_desc
    picture = GFX_Generic_COVID1
    is_triggered_only = yes
    fire_only_once = yes
    trigger = {
        tag = EST
        date > 2020.2.26
        date < 2023.1.1
        NOT = { has_country_flag = TFR_EST_covid_first_case_recorded }
    }
    immediate = { TFR_EST_register_covid_first_case = yes }
    option = { name = TFR_EST_covid_first_case_option }
}
"""


def build_localisation() -> str:
    entries = {
        "TFR_EST_covid_first_case_title": "Estonia Confirms Its First COVID-19 Case",
        "TFR_EST_covid_first_case_desc": (
            "The Health Board has announced Estonia's first confirmed case of COVID-19. "
            "Hospitals and health officials are coordinating the immediate response, while "
            "the cabinet must consider how to protect essential services and prepare for "
            "further infections. The outbreak has now reached Estonia; the coalition can "
            "begin its emergency-response programme."
        ),
        "TFR_EST_covid_first_case_option": "The cabinet must prepare its response.",
    }
    return "l_english:\n" + "".join(
        f" {key}:0 {json.dumps(value, ensure_ascii=False)}\n"
        for key, value in entries.items()
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check generated files without changing them.")
    args = parser.parse_args()
    outputs = (
        (ROOT / "common/scripted_effects/TFR_EST_covid.txt", build_effects().encode("utf-8")),
        (ROOT / "events/TFR_EST_covid.txt", build_events().encode("utf-8")),
        (ROOT / "localisation/english/TFR_EST_covid_l_english.yml", build_localisation().encode("utf-8-sig")),
    )
    for path, data in outputs:
        if args.check:
            if not path.is_file() or path.read_bytes() != data:
                raise SystemExit(f"Generated file is stale: {path.relative_to(ROOT)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        print(f"{path.relative_to(ROOT).as_posix()}: {hashlib.sha256(data).hexdigest()}")
    print(("Verified" if args.check else "Wrote") + " Estonia's first-case effects, event and three English localisation keys.")


if __name__ == "__main__":
    main()
