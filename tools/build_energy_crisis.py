"""Reuse TFR's actual oil-crash ideas for Estonia's energy-crisis recovery.

The GER_oil_crash1..5 family has generic names and artwork and is already used
outside Germany by TFR's own recovery effect. No parent idea is overridden.
Each equivalent policy slot earns one recovery stage. Kallas's network-charge
policy covers two slots, matching the established supply and household relief.
"""
from __future__ import annotations

import argparse
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
RELATIVE = "common/scripted_effects/TFR_EST_energy.txt"
IDEAS = tuple(f"GER_oil_crash{index}" for index in range(1, 6))
SLOTS = (
    ("lng_connection", "lng_connection"),
    ("grid_synchronisation", "gas_reserve"),
    ("renewable_chp", "energy_networks"),
    ("building_renovation", "energy_households"),
    ("network_charge_relief", "energy_networks"),
)
RATAS_PROJECTS = tuple(pair[0] for pair in SLOTS)
KALLAS_PROJECTS = tuple(dict.fromkeys(pair[1] for pair in SLOTS))
# Keep the older two-route SLOTS API stable for its exhaustive 512-case test.
# New preparations fill equivalent slots, never adding a second contribution.
REFORM_2023_SLOTS = ("grid_connection", "grid_connection", "wind_permits", "renovation", "renovation")
REFORM_2023_PROJECTS = tuple(dict.fromkeys(REFORM_2023_SLOTS))
EKRE_2023_SLOTS = ("narva_blocks", "narva_blocks", "kiisa_reserve", "regulated_power", "regulated_power")
EKRE_2023_PROJECTS = tuple(dict.fromkeys(EKRE_2023_SLOTS))
CENTRE_2023_SLOTS = ("power_reserves", "power_reserves", "local_chp", "apartment_renovation", "apartment_renovation")
CENTRE_2023_PROJECTS = tuple(dict.fromkeys(CENTRE_2023_SLOTS))


def idea_cleanup(keep: str | None = None, indent: str = "        ") -> str:
    return "\n".join(
        f"{indent}if = {{ limit = {{ has_idea = {idea} }} remove_ideas = {idea} }}"
        for idea in IDEAS if idea != keep
    )


def build_effects() -> str:
    text = """# Generated by tools/build_energy_crisis.py. Parent ideas retain their real modifiers.
# Back out the former custom dynamic contribution once, preserving reforms.
TFR_EST_migrate_energy_crisis_ledger = {
    if = {
        limit = { tag = EST has_country_flag = TFR_EST_initialized }
        if = {
            limit = {
                OR = {
                    NOT = { has_variable = TFR_EST_economy_industrial_capacity_factory_var }
                    NOT = { has_variable = TFR_EST_economy_consumer_goods_factor_var }
                }
            }
            TFR_EST_initialize_country_modifiers = yes
        }
        if = { limit = { NOT = { has_variable = TFR_EST_energy_factory_applied } } set_variable = { TFR_EST_energy_factory_applied = 0 } }
        if = { limit = { NOT = { has_variable = TFR_EST_energy_goods_applied } } set_variable = { TFR_EST_energy_goods_applied = 0 } }
        if = {
            limit = {
                OR = {
                    check_variable = { var = TFR_EST_energy_factory_applied value = 0 compare = not_equals }
                    check_variable = { var = TFR_EST_energy_goods_applied value = 0 compare = not_equals }
                }
            }
            subtract_from_variable = { var = TFR_EST_economy_industrial_capacity_factory_var value = TFR_EST_energy_factory_applied }
            subtract_from_variable = { var = TFR_EST_economy_consumer_goods_factor_var value = TFR_EST_energy_goods_applied }
            set_variable = { TFR_EST_energy_factory_applied = 0 }
            set_variable = { TFR_EST_energy_goods_applied = 0 }
            TFR_EST_refresh_country_modifiers = yes
        }
    }
}

TFR_EST_reconcile_energy_crisis = {
    if = {
        limit = { tag = EST has_country_flag = TFR_EST_initialized }
        TFR_EST_migrate_energy_crisis_ledger = yes
        set_variable = { TFR_EST_energy_response_steps = 0 }
"""
    for (ratas, kallas), reform, ekre, centre in zip(SLOTS, REFORM_2023_SLOTS, EKRE_2023_SLOTS, CENTRE_2023_SLOTS):
        text += f"""        if = {{
            limit = {{ OR = {{ has_country_flag = TFR_EST_done_ratas_{ratas} has_country_flag = TFR_EST_done_kallas_{kallas} has_country_flag = TFR_EST_done_reform_2023_{reform} has_country_flag = TFR_EST_done_ekre_2023_{ekre} has_country_flag = TFR_EST_done_centre_2023_{centre} }} }}
            add_to_variable = {{ TFR_EST_energy_response_steps = 1 }}
        }}
"""
    text += f"""        if = {{
            limit = {{ TFR_EST_energy_crisis_active = yes }}
            if = {{
                limit = {{ NOT = {{ has_country_flag = TFR_EST_energy_crisis_seen }} }}
                set_country_flag = TFR_EST_energy_crisis_seen
                country_event = {{ id = tfr_estonia_ratas.1 }}
            }}
            # Adopt an already present weaker parent tier, never worsen or stack it.
            if = {{
                limit = {{ NOT = {{ has_country_flag = TFR_EST_energy_idea_managed }} }}
                set_country_flag = TFR_EST_energy_idea_managed
                set_variable = {{ TFR_EST_energy_external_recovery = 0 }}
"""
    for steps in range(4, 0, -1):
        kind = "if" if steps == 4 else "else_if"
        text += f"                {kind} = {{ limit = {{ has_idea = GER_oil_crash{steps + 1} }} set_variable = {{ TFR_EST_energy_external_recovery = {steps} }} }}\n"
    text += """            }
            set_temp_variable = { var = TFR_EST_energy_effective_recovery value = TFR_EST_energy_response_steps }
            add_to_temp_variable = { var = TFR_EST_energy_effective_recovery value = TFR_EST_energy_external_recovery }
            clamp_temp_variable = { var = TFR_EST_energy_effective_recovery min = 0 max = 5 }
            if = {
                limit = { check_variable = { var = TFR_EST_energy_effective_recovery value = 5 compare = equals } }
"""
    text += idea_cleanup(indent="                ") + "\n            }\n"
    for steps in range(4, -1, -1):
        idea = IDEAS[steps]
        text += f"""            else_if = {{
                limit = {{ check_variable = {{ var = TFR_EST_energy_effective_recovery value = {steps} compare = equals }} }}
{idea_cleanup(idea, indent="                ")}
                if = {{ limit = {{ NOT = {{ has_idea = {idea} }} }} add_ideas = {idea} }}
            }}
"""
    text += f"""        }}
        else_if = {{
            limit = {{ has_country_flag = TFR_EST_energy_idea_managed }}
{idea_cleanup(indent="            ")}
        }}
    }}
}}
"""
    return text


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = ROOT / RELATIVE
    expected = build_effects().encode("utf-8")
    if args.check:
        if not path.is_file() or path.read_bytes() != expected:
            raise SystemExit(f"Generated energy crisis is stale: {RELATIVE}")
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(expected)
    print(("Verified" if args.check else "Wrote") + " TFR oil-crash idea integration and dynamic-ledger migration.")


if __name__ == "__main__":
    main()
